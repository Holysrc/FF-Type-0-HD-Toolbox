"""Generate reviewed scene profiles from the locally cached whole-game audit.

No game/source assets are embedded: only scene/command IDs and fingerprints.
Run audit_cutscene_gates.py --package ... first to populate dump/cutscene_audit.
"""
import argparse
import json
from pathlib import Path
import struct
from audit_cutscene_gates import atels, OUT, ROOT

# Reviewed external CMD5F()>2 gates; offsets identify whole ATELY modules.
EXTERNAL = [
    ('main0103', 0x7320, 0x1BE, 7156),
    ('main0302', 0x16F10, 0x1894, 7301),
    ('main0302', 0x1E420, 0xDC, 7301),
    ('main0401', 0x1F0E0, 0xF4A, 7452),
    ('main0402', 0x5440, 0x39C, 7453),
    ('main0403', 0x14B40, 0x2D2, 7455),
    ('main0403', 0x26450, 0x1D4, 7458),
    ('main0500', 0xF4F0, 0x1BF6, 7551),
    ('main0503', 0x15CE0, 0x64E, 7555),
    ('main0505', 0x19A00, 0x203A, 7553),
    ('main0505', 0x1C830, 0x2216, 7554),
]
# PC_0..2 animation tracks, including implicit targets selected by CMD219.
# Boss/NPC clips are intentionally excluded. Empty tuples use native casting.
CLIPS = {7156:(71,73), 7157:(), 7158:(), 7159:(), 7301:(71,),
         7355:(), 7452:(71,), 7453:(71,), 7455:(71,72,2400),
         7458:(71,), 7459:(), 7551:(67,68,71), 7553:(71,73,2400),
         7554:(71,2400), 7555:(7,67,68,69,71,2400), 7558:(), 7752:()}
INTERNAL = {7157:4,7158:4,7159:4,7355:2,7459:2,7558:2,7752:4}

def fingerprint(data):
    value = 14695981039346656037
    for b in data:
        value = ((value ^ b) * 1099511628211) & 0xffffffffffffffff
    return value

def collect():
    entries=json.loads((OUT/'manifest.json').read_text())
    def module(stem, offset=None):
        entry=next(e for e in entries if Path(e['name']).stem==stem)
        modules=list(atels((OUT/entry['cache']).read_bytes()))
        if offset is None:
            assert len(modules)==1
            return modules[0]
        return next(m for m in modules if m[0]==offset)
    profiles=[];guards=[]
    for scene, clips in sorted(CLIPS.items()):
        _,code,pool,names=module(f'cut{scene}')
        profiles.append((scene,len(code),pool,fingerprint(code),clips))
        if scene in INTERNAL:
            needle=bytes.fromhex('f2 05 fc 0f 00 00')
            pcs=[i+6 for i in range(48,names-5,2) if code[i:i+6]==needle]
            assert len(pcs)==INTERNAL[scene]
            for pc in pcs:
                constant,op=struct.unpack_from('<HH',code,pc)
                threshold=struct.unpack_from('<f',code,pool+(constant>>6)*4)[0]
                assert constant&15==4 and (threshold,op) in ((0.0,0x136),(3.0,0x126))
                guards.append((scene,pc,len(code),pool,fingerprint(code),True))
    for stem,offset,pc,scene in EXTERNAL:
        _,code,pool,_=module(stem,offset)
        assert code[pc-6:pc]==bytes.fromhex('f2 05 fc 0f 00 00')
        constant,op=struct.unpack_from('<HH',code,pc)
        assert constant&15==4 and op==0x136
        assert struct.unpack_from('<f',code,pool+(constant>>6)*4)[0]==2
        # Playback operand exists in this module; full fingerprint pins all
        # intervening guards/setup/cleanup, not just proximity to CMD12.
        assert struct.pack('<f',scene) in code[pool:]
        guards.append((scene,pc,len(code),pool,fingerprint(code),False))
    return profiles,guards

def render():
    profiles,guards=collect()
    lines=['// Generated by docs/tools/build_cutscene_profiles.py. Do not edit.',
           '// Reviewed coverage and limitations: docs/CUTSCENE_PARTY_EXPANSION.md.',
           '#pragma once','#include <cstddef>','#include <cstdint>','#include <cstring>',
           'namespace CutscenePartyProfiles {',
           'struct Profile { int scene; uint32_t size, pool; uint64_t hash; int clips[8]; unsigned clipCount; };',
           'struct Guard { int scene; uint32_t pc, size, pool; uint64_t hash; bool internal; };',
           'inline constexpr Profile profiles[] = {']
    for scene,size,pool,h,clips in profiles:
        lines.append(f'    {{{scene}, {size}, {pool}, 0x{h:016X}ULL, {{{",".join(map(str,clips))}}}, {len(clips)}}},')
    lines+=['};','inline constexpr Guard guards[] = {']
    for scene,pc,size,pool,h,inside in guards:
        lines.append(f'    {{{scene}, 0x{pc:X}, {size}, {pool}, 0x{h:016X}ULL, {str(inside).lower()}}},')
    lines+=['};',
        'inline uint64_t Fingerprint(const uint8_t* data, size_t size) {',
        '    uint64_t hash = 14695981039346656037ULL;',
        '    for (size_t i = 0; i < size; ++i) hash = (hash ^ data[i]) * 1099511628211ULL;',
        '    return hash;', '}',
        'inline const Profile* Find(int scene) {',
        '    for (const auto& p : profiles) if (p.scene == scene) return &p;',
        '    return nullptr;', '}',
        'inline bool Scope(int armed, int current, int stage) {',
        '    return Find(armed) && current == armed && stage >= 5 && stage <= 8;', '}',
        'inline bool MissingActor(int channel, const char* name, int armed, int current, int stage, unsigned empty) {',
        '    if (!Find(armed) || armed != current || stage < 4 || stage > 11 || !name) return false;',
        '    if (std::strcmp(name,"PC_0") && std::strcmp(name,"PC_1") && std::strcmp(name,"PC_2")) return false;',
        "    const int slot = name[3] - '0';",
        '    return channel == -1 || (channel == slot && (empty & (1u << slot)));', '}',
        'inline bool Eligible(const Guard& guard, unsigned pc, float alive, int prepared, int current, int stage) {',
        '    return guard.pc == pc && (alive == 1 || alive == 2) &&',
        '        (!guard.internal || (prepared == guard.scene && Scope(prepared, current, stage)));', '}',
        '}','']
    return '\n'.join(lines)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true');args=parser.parse_args()
    target=ROOT/'source/include/CutscenePartyProfiles.h';text=render()
    if args.check:
        assert target.read_text()==text, 'Generated profiles are stale'
    else: target.write_text(text,encoding='utf-8')
    profiles,guards=collect()
    print(f'{len(profiles)} reviewed scenes, {len(guards)} exact-module guard sites; profiles verified')
